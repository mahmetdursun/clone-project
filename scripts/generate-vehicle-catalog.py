#!/usr/bin/env python3
"""
Generates src/components/sites/sonparca-com-32cbe5a4/bakim-robotu-48003cd4/
vehicle-catalog-tr.ts from the Türkiye Araç Kataloğu 1970-2026 reference
spreadsheet (docs/research/vehicle-catalog-tr-1970-2026/).

Re-run this whenever that source file is replaced with a newer/more complete
one (e.g. once the brand/model data from the other project is merged in):

    pip install openpyxl --break-system-packages
    python3 scripts/generate-vehicle-catalog.py

The spreadsheet has three relevant sheets:
  - "Katalog 1970-2026": one row per model/engine/package variant. Columns
    (0-indexed): Kategori, Marka, Seri/Model, Motor, Paket, Kasa, Yakıt,
    Yakıt Tahmini mi?, Vites, Çekiş, İlk Model Yılı, Son Model Yılı,
    Model Yılları, Orijinal Ad, TSB Araç Kodu, Türkiye Notu, Kaynak.
  - "Markalar" / "Seriler": brand- and series-level summaries (not used here
    — we aggregate straight from the per-variant rows instead, so brand/model
    groupings always stay consistent with VEHICLE_SPECS).

2006-2026 rows come from the Türkiye Sigorta Birliği (TSB) Kasko Değer
Listesi — vehicles confirmed sold in Turkey, at package/trim level.
1970-2005 rows come from the "vehicle-makes-models" open dataset
(github.com/gor3a/vehicle-makes-models, sourced from autoevolution.com,
ODbL-licensed), plus a handful of Turkish-made models added by hand from
Wikipedia (Tofaş/Anadol/Ford Otosan/Oyak-Renault). That older range has NOT
been verified against actual Turkish-market sales — some entries may be
international-market models never sold here (flagged in the sheet's own
"Türkiye Notu" column as "Türkiye satışı doğrulanmadı").
"""

import json
import re
from collections import defaultdict
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/research/vehicle-catalog-tr-1970-2026/Turkiye_Arac_Katalogu_1970-2026.xlsx"
OUT = (
    ROOT
    / "src/components/sites/sonparca-com-32cbe5a4/bakim-robotu-48003cd4/vehicle-catalog-tr.ts"
)

# Brand-name fragments that should stay fully upper-case when we convert the
# source sheet's ALL-CAPS brand names into nicer display casing (e.g.
# "ALFA ROMEO" -> "Alfa Romeo", but "BMW" -> "BMW", not "Bmw").
ACRONYMS = {
    "BMW", "BMC", "BYD", "DFM", "DFSK", "FAW", "GAC", "GMC", "IKCO", "JAC",
    "KTM", "MG", "SWM", "WMA", "XEV", "DS", "GAZ", "KG", "CNG", "EMT", "PGO",
}


def display_brand(raw: str) -> str:
    raw = raw.strip()
    parts = re.split(r"(\s|-|&)", raw)
    out = []
    for p in parts:
        if p in (" ", "-", "&") or p == "":
            out.append(p)
            continue
        out.append(p.upper() if p.upper() in ACRONYMS else p.capitalize())
    return "".join(out)


def parse_years(s: str) -> list[int]:
    s = s.strip()
    if re.fullmatch(r"\d{4}-\d{4}", s):
        a, b = s.split("-")
        return list(range(int(a), int(b) + 1))
    return [int(x) for x in s.split(",")]


def ts_str_array(items: list[str]) -> str:
    return "[" + ", ".join(json.dumps(x, ensure_ascii=False) for x in items) + "]"


def main() -> None:
    wb = openpyxl.load_workbook(SRC, data_only=True)
    ws = wb["Katalog 1970-2026"]
    rows = list(ws.iter_rows(min_row=2, values_only=True))

    model_specs: dict[str, dict[str, dict[str, set]]] = defaultdict(
        lambda: defaultdict(lambda: {"years": set(), "fuels": set(), "engines": set()})
    )

    for r in rows:
        (
            _kategori, marka, model, motor, _paket, _kasa, yakit, _yakit_tahmin,
            _vites, _cekis, _ilk_yil, _son_yil, model_yillari, _orijinal_ad,
            _tsb_kod, _tr_notu, _kaynak,
        ) = r
        if not marka or not model:
            continue
        marka = marka.strip()
        model = str(model).strip()
        entry = model_specs[marka][model]
        entry["years"].update(parse_years(model_yillari))
        if yakit:
            entry["fuels"].add(yakit.strip())
        if motor:
            entry["engines"].add(str(motor).strip())

    brands_sorted = sorted(model_specs.keys(), key=display_brand)

    lines: list[str] = []
    lines.append("// AUTO-GENERATED by scripts/generate-vehicle-catalog.py — do not hand-edit.")
    lines.append("// Re-run that script after replacing the source file; see its module")
    lines.append("// docstring for the data provenance (TSB Kasko Değer Listesi 2006-2026 +")
    lines.append("// vehicle-makes-models/autoevolution + Wikipedia for 1970-2005).")
    lines.append("")
    lines.append('import type { VehicleModelSpecs } from "./data";')
    lines.append("")
    lines.append("export const VEHICLE_BRANDS: string[] = [")
    for b in brands_sorted:
        lines.append(f"  {json.dumps(display_brand(b), ensure_ascii=False)},")
    lines.append("];")
    lines.append("")
    lines.append("export const VEHICLE_MODELS_BY_BRAND: Record<string, string[]> = {")
    for b in brands_sorted:
        models_sorted = sorted(model_specs[b].keys())
        lines.append(
            f"  {json.dumps(display_brand(b), ensure_ascii=False)}: "
            f"{ts_str_array(models_sorted)},"
        )
    lines.append("};")
    lines.append("")
    lines.append(
        "export const VEHICLE_SPECS: Record<string, Record<string, VehicleModelSpecs>> = {"
    )
    for b in brands_sorted:
        lines.append(f"  {json.dumps(display_brand(b), ensure_ascii=False)}: {{")
        for m in sorted(model_specs[b].keys()):
            entry = model_specs[b][m]
            years = sorted(entry["years"])
            fuels = sorted(entry["fuels"])
            engines = sorted(entry["engines"])
            years_str = "[" + ", ".join(str(y) for y in years) + "]"
            lines.append(
                f"    {json.dumps(m, ensure_ascii=False)}: {{ years: {years_str}, "
                f"fuels: {ts_str_array(fuels)}, engines: {ts_str_array(engines)} }},"
            )
        lines.append("  },")
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} — {len(brands_sorted)} brands, "
          f"{sum(len(m) for m in model_specs.values())} models.")


if __name__ == "__main__":
    main()
